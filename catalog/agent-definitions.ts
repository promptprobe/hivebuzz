export interface AgentCatalogSource {
  slug: string;
  releaseId: string;
  displayName: string;
  version: string;
  category: AgentCategory;
  summary: string;
  description: string;
  about: string;
  keywords: readonly string[];
  recommendedHarness: AgentHarness;
  recommendedModel: string;
  addedAt: number;
  preserveArtifact?: true;
  prompt?: PromptBlueprint;
}

const launch = 1_787_270_400;

function ready(
  index: number,
  source: Omit<AgentCatalogSource, "addedAt" | "recommendedModel"> & { recommendedModel?: string },
): AgentCatalogSource {
  return {
    ...source,
    addedAt: launch - (index * 60),
    recommendedModel: source.recommendedModel ?? "Provider default",
  };
}

